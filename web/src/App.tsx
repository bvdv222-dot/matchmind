import { useEffect, useMemo, useState } from "react";
import { api, useLive, usePoll } from "./api";
import { AnalystView } from "./components/Analyst";
import { MomentCards, NoteFeed, PlayerTags, ScoreBug, WinProbBar } from "./components/Broadcast";
import { LivePitch } from "./components/Pitch";
import { AgentTrace, AskPanel, PlayerCard } from "./components/Side";
import type { Fixture } from "./types";

type Tab = "broadcast" | "analyst" | "player" | "agents";

function FixturePicker({ onStart }: { onStart: (id: string, speed: number) => void }) {
  const [round, setRound] = useState(1);
  const [speed, setSpeed] = useState(10);    // local models keep up at 10x; Foundry can go faster
  const [fixtures, setFixtures] = useState<Fixture[]>([]);
  useEffect(() => { api.fixtures(round).then(r => setFixtures(r.fixtures)).catch(() => setFixtures([])); }, [round]);
  return (
    <div className="picker">
      <div className="picker-head">
        <h2>Premier Synthetic League · 2026/27</h2>
        <label>Round <select value={round} onChange={e => setRound(+e.target.value)}>
          {[...Array(38)].map((_, i) => <option key={i} value={i + 1}>{i + 1}</option>)}</select></label>
        <label>Speed <select value={speed} onChange={e => setSpeed(+e.target.value)}>
          {[5, 10, 20, 40, 90].map(s => <option key={s} value={s}>{s}× ({Math.round(95 / s)} min)</option>)}</select></label>
      </div>
      <div className="fixture-grid">
        {fixtures.map(f => (
          <button key={f.match_id} className="fixture" onClick={() => onStart(f.match_id, speed)}>
            <span className="fx-teams">{f.home} <em>v</em> {f.away}</span>
            <span className="fx-meta">{new Date(f.kickoff_utc).toUTCString().slice(0, 22)} · {f.live ? "live" : f.status}</span>
          </button>
        ))}
      </div>
      <p className="muted small">Every match, club and player here is synthetic: generated by a model calibrated on real
        Premier League data (Wyscout 2017/18, CC BY 4.0). Notes are written by AI agents and checked by code before they appear.</p>
    </div>
  );
}

export default function App() {
  const [matchId, setMatchId] = useState<string | null>(null);
  const [tab, setTab] = useState<Tab>("broadcast");
  const [persona, setPersona] = useState("casual");
  const [lang, setLang] = useState("en");
  const [focus, setFocus] = useState<string | null>(null);
  const [askTeam, setAskTeam] = useState<string | null>(null);
  const cfg = usePoll(api.config, 60_000, []);
  const live = useLive(matchId, persona, lang, focus);
  const dash = usePoll(matchId && (tab === "analyst" || tab === "agents") ? () => api.dashboard(matchId) : null, 3000, [matchId, tab]);
  const player = usePoll(matchId && focus ? () => api.player(matchId, focus) : null, 3000, [matchId, focus]);
  const trace = usePoll(matchId && tab === "agents" ? () => api.agents(matchId) : null, 4000, [matchId, tab]);

  const start = async (id: string, speed: number) => {
    const langs = Object.keys(cfg?.languages ?? {}).includes(lang) && lang !== "en" ? [lang] : ["es"];
    await api.start(id, speed, langs);
    setMatchId(id);
    setTab("broadcast");
  };

  const roster = useMemo(() => {
    const m = live.meta;
    if (!m) return [];
    return [m.home, m.away].flatMap(t => [...t.starting, ...t.bench].map(p => ({ ...p, team: t.short_name, team_id: t.team_id })));
  }, [live.meta]);

  const personaOptions = live.personas.map(p => {
    const label = p.club_id ? `${p.label}: ${live.meta?.home.team_id === p.club_id ? live.meta?.home.name : live.meta?.away.name}` : p.label;
    return { id: p.persona_id, label };
  }).filter(p => !p.id.startsWith("player_"));
  if (focus) personaOptions.push({ id: "player", label: "Player focus" });

  const pick = (pid: string) => { setFocus(pid); setTab(t => (t === "broadcast" ? t : "player")); };

  return (
    <div className="app">
      <header className="top">
        <button className="brand" onClick={() => setMatchId(null)} title="Choose a match">Match<span>Mind</span></button>
        {matchId && live.meta && (
          <nav className="tabs" aria-label="Views">
            {(["broadcast", "analyst", "player", "agents"] as Tab[]).map(t => (
              <button key={t} className={tab === t ? "on" : ""} onClick={() => setTab(t)}>
                {{ broadcast: "Broadcast", analyst: "Analyst", player: "Player focus", agents: "Agents" }[t]}
              </button>
            ))}
          </nav>
        )}
        <div className="prefs">
          {matchId && (
            <label>Viewer <select value={persona} onChange={e => setPersona(e.target.value)}>
              {personaOptions.map(p => <option key={p.id} value={p.id}>{p.label}</option>)}</select></label>
          )}
          <label>Language <select value={lang} onChange={e => setLang(e.target.value)}>
            {Object.entries(cfg?.languages ?? { en: "English" }).map(([k, v]) => <option key={k} value={k}>{v}</option>)}</select></label>
          <span className={`dot ${live.connected ? "on" : ""}`} title={live.connected ? "live feed connected" : "not connected"} />
          {cfg && <span className="model" title={JSON.stringify(cfg.models.models)}>{cfg.agents ? `agents: ${cfg.models.provider}` : "agents off"}</span>}
        </div>
      </header>

      {!matchId && <FixturePicker onStart={start} />}

      {matchId && live.meta && live.state && (
        <main className={`view view-${tab}`}>
          {tab === "broadcast" && (
            <div className="broadcast">
              <div className="stage">
                <LivePitch frame={live.frame} meta={live.meta} focus={focus} onPick={pick} />
                <div className="overlay-top"><ScoreBug meta={live.meta} state={live.state} /><PlayerTags tags={live.tags} /></div>
                <MomentCards cards={live.cards} />
                <div className="overlay-bottom"><WinProbBar meta={live.meta} state={live.state} /></div>
                {live.finished && <div className="ft-banner">Full time</div>}
              </div>
              <aside className="side">
                <h3>Live notes <small>{personaOptions.find(p => p.id === persona)?.label}</small></h3>
                <NoteFeed notes={live.notes} lang={lang} />
              </aside>
              <AskPanel matchId={matchId} tab={tab} teamId={null} playerId={null} persona={persona} lang={lang} />
            </div>
          )}

          {tab === "analyst" && (dash ? (
            <>
              <AnalystView d={dash} meta={live.meta} onTeam={tid => setAskTeam(tid)} onPlayer={pid => { setFocus(pid); setTab("player"); }} />
              <AskPanel matchId={matchId} tab={tab} teamId={askTeam} playerId={null} persona={persona} lang={lang} />
            </>
          ) : <p className="muted pad">Loading the analysis…</p>)}

          {tab === "player" && (
            <div className="player-view">
              <aside className="roster">
                {[live.meta.home, live.meta.away].map(t => (
                  <div key={t.team_id}><h4>{t.name}</h4>
                    {roster.filter(p => p.team_id === t.team_id).map(p => (
                      <button key={p.player_id} className={`rp ${focus === p.player_id ? "on" : ""}`} onClick={() => setFocus(p.player_id)}>
                        <span className="rp-n">{p.shirt}</span>{p.name}<span className="muted"> {p.position}</span>
                      </button>
                    ))}
                  </div>
                ))}
              </aside>
              <div className="pv-main">
                <div className="stage small"><LivePitch frame={live.frame} meta={live.meta} focus={focus} onPick={pick} /></div>
                {player ? <PlayerCard p={player} meta={live.meta} /> : <p className="muted pad">Pick a player to follow. Choose "Player focus" as the viewer to get notes centred on them.</p>}
                {focus && <AskPanel matchId={matchId} tab={tab} teamId={null} playerId={focus} persona={persona} lang={lang} />}
              </div>
            </div>
          )}

          {tab === "agents" && (
            <div className="agents-view">
              <AgentTrace notes={trace?.notes ?? []} />
              <section className="panel">
                <h3>Models</h3>
                <ul className="models">{Object.entries(cfg?.models.models ?? {}).map(([r, m]) => <li key={r}><b>{r}</b> {m}</li>)}</ul>
                <p className="small muted">Provider: {cfg?.models.provider}. Gather, Facts, Verifier and Publish are code; models only choose the story and write.</p>
              </section>
              <section className="panel facts">
                <h3>Fact sheet the agents write from</h3>
                <ul>{(dash?.facts ?? []).map(f => <li key={f.key}>{f.text}</li>)}</ul>
              </section>
            </div>
          )}
        </main>
      )}
      {matchId && !live.meta && <p className="muted pad">Connecting to the live feed…</p>}
    </div>
  );
}
